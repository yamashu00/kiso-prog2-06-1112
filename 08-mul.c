//   関数形式マクロでは「引数を1つずつカッコで囲む」必要があることを、自分で確かめる
//
// 【やること】
//   2つの整数の積を求める関数形式マクロ MUL を定義して、プログラムを完成させる
//
// 【手順】
//   1. 下の「#define MUL(a, b) 0   /* ここを書き換える */」の行の 0 の部分を書き換える
//   2. gcc 08-mul.c -o 08-mul を実行する
//   3. ./08-mul を実行し、「2+3 と 4 の積は20 です」と表示されれば完成
//   4. 14 になったときは、gcc -E 08-mul.c -o 08-mul.i を実行し、
//      tail -n 6 08-mul.i で MUL(2 + 3, 4) がどんな式に置き換わったか確かめて、#define を直す
//
// 【確認できたらOK】
//   ・「2+3 と 4 の積は20 です」と表示された
//
// 【やってみよう】
//   ① 関数形式マクロの利点と欠点を、今日のスライドを見ながら自分の言葉でコメントに書く
// ==================================================
#include <stdio.h>
#define MUL(a, b) 0   /* ここを書き換える */

int main(void)
{
    printf("2+3 と 4 の積は%d です\n", MUL(2 + 3, 4));
    return 0;
}
