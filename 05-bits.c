// 【目的】
//   関数形式マクロを自分で定義できるようになる
//
// 【やること】
//   バイト数をビット数に変換する関数形式マクロ BITS を定義して、プログラムを完成させる
//
// 【手順】
//   1. 下の「#define BITS(b) 0   /* ここを書き換える */」の行の 0 の部分を書き換える
//        ・ヒント：1バイトは8ビット。引数 b はカッコで囲む
//   2. gcc 05-bits.c -o 05-bits を実行する
//   3. ./05-bits を実行し、4 を入力する
//   4. 「4 バイトは32 ビットです」と表示されれば完成
//        ・うまくいかないときは gcc -E 05-bits.c -o 05-bits.i を実行し、
//          tail -n 10 05-bits.i で BITS(byte) がどんな式に置き換わったか確かめる
//
// 【確認できたらOK】
//   ・4 を入力して「4 バイトは32 ビットです」と表示された
//
// 【やってみよう】
//   ① printf の中の BITS(byte) を BITS(byte + 1) に変えて、4 を入力すると 40 になるか確かめる
// ==================================================
#include <stdio.h>
#define BITS(b) 0   /* ここを書き換える */

int main(void)
{
    int byte;
    printf("整数=");
    scanf("%d", &byte);
    printf("%d バイトは%d ビットです\n", byte, BITS(byte));
    return 0;
}
