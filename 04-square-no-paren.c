// 【目的】
//   マクロのカッコを外すと、思わぬ計算になることを確かめる。
//   #define は「意味を考えず、文字をそのまま置き換えるだけ」なので、カッコが必要になる
//
// 【登場するファイル】
//   ・04-square-no-paren.c …… 材料（このファイル）。03 の SQUARE からカッコを外したもの
//   ・04-square-no-paren.i …… 結果（手順4で自分で作る）。見るだけのファイル
//
// 【手順】
//   1. 実行する前に予想する：r + 1 は 4 なので、2乗は 16 になるはず…？
//   2. gcc 04-square-no-paren.c -o 04-square-no-paren を実行する
//   3. ./04-square-no-paren を実行し、表示された数を確かめる（予想と同じだった？）
//   4. gcc -E 04-square-no-paren.c -o 04-square-no-paren.i を実行する
//   5. tail -n 6 04-square-no-paren.i を実行し、SQUARE(r + 1) がどんな式に置き換わったかを見る
//   6. その式を、掛け算を先に計算するルールで計算して、手順3の結果になる理由を説明する
//
// 【確認できたらOK】
//   ・手順3の結果が 16 にならない理由を、手順5の式を使って説明できた
//
// 【やってみよう】
//   ① #define の行をどう直せば 16 になる？ 03-square-macro.c と見比べて直し、手順2〜3で確かめる
// ==================================================
#include <stdio.h>
#define SQUARE(a) (a * a)   /* カッコを外した */

int main(void)
{
    int r = 3;
    printf("2乗は%dです。\n", SQUARE(r + 1));   /* 1足した */
    return 0;
}
