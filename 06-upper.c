// 【目的】
//   文字が「数（文字コード）」であることを使って、関数形式マクロを定義できるようになる
//
// 【やること】
//   小文字を大文字に変換する関数形式マクロ UPPER を定義して、プログラムを完成させる
//
// 【手順】
//   1. 下の「#define UPPER(c) (c)   /* ここを書き換える */」の行の (c) の部分を書き換える
//        ・ヒント：'a' と 'A' は文字コードが一定の差だけ離れている（1年で学んだASCIIコード）
//          例：'c' − 'a' は 2。'A' に 2 を足すと 'C'
//   2. gcc 06-upper.c -o 06-upper を実行する
//   3. ./06-upper を実行し、a を入力する
//   4. 「大文字に変換するとA です」と表示されれば完成（z を入力して「Z」になるかも確かめる）
//
// 【確認できたらOK】
//   ・a を入力して「A」、z を入力して「Z」と表示された
//
// 【やってみよう】
//   ① 大文字（例：B）を入力すると、どうなる？ 三項演算子を使って、小文字のときだけ変換するように直す
// ==================================================
#include <stdio.h>
#define UPPER(c) (c)   /* ここを書き換える */

int main(void)
{
    char c;
    printf("小文字を入力してください=");
    scanf("%c", &c);
    printf("大文字に変換すると%c です\n", UPPER(c));
    return 0;
}
