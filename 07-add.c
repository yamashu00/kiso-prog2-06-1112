// 【目的】
//   関数形式マクロでは「全体をカッコで囲む」必要があることを、自分で確かめる
//
// 【やること】
//   2つの整数の和を求める関数形式マクロ ADD を定義して、プログラムを完成させる
//
// 【手順】
//   1. 下の「#define ADD(a, b) 0   /* ここを書き換える */」の行の 0 の部分を書き換える
//   2. gcc 07-add.c -o 07-add を実行する
//   3. ./07-add を実行し、3 と 4 を入力する
//   4. 次の2行が表示されれば完成
//        3 + 4 = 7
//        3 + 4 の2倍は14 です
//   5. 2行目が 14 にならないときは、gcc -E 07-add.c -o 07-add.i を実行し、
//      tail -n 12 07-add.i で ADD(i1, i2) * 2 がどんな式に置き換わったか確かめて、#define を直す
//
// 【確認できたらOK】
//   ・3 と 4 を入力して、2行目が「3 + 4 の2倍は14 です」になった
//
// 【やってみよう】
//   ① 2行目が 14 にならない書き方と、14 になる書き方の違いを、ペアの人に説明する
// ==================================================
#include <stdio.h>
#define ADD(a, b) 0   /* ここを書き換える */

int main(void)
{
    int i1, i2;

    printf("整数1=");  scanf("%d", &i1);
    printf("整数2=");  scanf("%d", &i2);

    printf("%d + %d = %d\n", i1, i2, ADD(i1, i2));
    printf("%d + %d の2倍は%d です\n", i1, i2, ADD(i1, i2) * 2);
    return 0;
}
